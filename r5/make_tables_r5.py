"""Generate the round-5 LaTeX macros and tables from committed aggregate results (no private inputs).
Writes paper_workshop/tables/numbers_r5.tex and tab_{r5_gates,r5_confirm,r5_worlds,calib_insample,prereg_r5}.tex.
Usage: python r5/make_tables_r5.py  (run after r4/make_tables_r4.py)."""
import os, sys, json, math
R = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
sys.path.insert(0, os.path.join(R, 'r4'))
from make_tables_r4 import f, mm, ci, NAME, ORDER, BASES, EST  # noqa: E402  (re-running r4 tables is idempotent)
OUT = os.path.join(R, 'paper_workshop', 'tables')
J = lambda p: json.load(open(os.path.join(R, p)))
G = J('r5/results/R5_gates.json'); C = J('r5/results/R5_confirm.json'); CMP = J('r5/results/R5_calibration_old_vs_new.json')
OLD = J('r4/results/I2_calibration.json')
P = G['models']; SM = G['summary']; NW = ('zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven', 'twelve', 'thirteen')
mac = {}
def M(k, v): mac[k] = v
def write(name, body): open(os.path.join(OUT, name), 'w').write('% generated by r5/make_tables_r5.py -- do not edit\n' + body)
def tci(d): return mm(f'{f(d["tau"])}\\ {ci(d)}')
SN = dict(SO='SO', XCC24='XCC')

# ---- calibration fix
M('CalChanged', str(CMP['n_changed'])); M('CalTotal', str(CMP['n_total']))
M('CalDiagOld', 'none' if not any(CMP['content_diagnostic_old'].values()) else 'some')
M('CalDiagNew', 'none' if not any(CMP['content_diagnostic_new'].values()) else 'some')
o = lambda b, W, e: OLD['bases'][b]['worlds'][W]['tau'][e]
M('OldNcmCalMLo', f(min(o(b, 'M', 'NCM_null') for b in BASES))); M('OldNcmCalMHi', f(max(o(b, 'M', 'NCM_null') for b in BASES)))
M('OldNcmCalCRN', f(o('resnet', 'C', 'NCM_null'))); M('OldNcmCalMDino', f(o('dinov2', 'M', 'NCM_null'))); M('NcmCalMDino', f(J('r4/results/I2_calibration_v2.json')['bases']['dinov2']['worlds']['M']['tau']['NCM_null'])); M('NewXCalCRN', f(J('r4/results/I2_calibration_v2.json')['bases']['resnet']['worlds']['C']['tau']['X'])); M('OldXCalCRN', f(o('resnet', 'C', 'X')))
body = '\\begin{tabular}{@{}l' + 'ccc' * 3 + '@{}}\n\\toprule\n & \\multicolumn{3}{c}{World C} & \\multicolumn{3}{c}{World M} & \\multicolumn{3}{c}{World D} \\\\\nEstimator & ' + ' & '.join(['RN50', 'RNX', 'DINOv2'] * 3) + ' \\\\\n\\midrule\n'
for e, lab in EST:
    cells = []
    for W in 'CMD':
        for b in BASES:
            v = o(b, W, e); cells.append('--' if v is None or (isinstance(v, float) and math.isnan(v)) else mm(f(v)))
    body += f'{lab} & ' + ' & '.join(cells) + ' \\\\\n'
body += '\\midrule\nexponent $a$ & ' + ' & '.join(mm(f(OLD['bases'][b]['worlds'][W]['exponent']['a'])) for W in 'CM' for b in BASES) + ' & \\multicolumn{3}{c}{--} \\\\\n'
write('tab_calib_insample.tex', body + '\\bottomrule\n\\end{tabular}\n')

# ---- gates per model
g = SM['gates']
for k in ('SO', 'XCC24'):
    s = SN[k]; d = g[k]
    M(f'{s}GOne', 'pass' if d['G1'] else 'fail'); M(f'{s}GTwoFail', str(len(d['G2_fail']))); M(f'{s}GThreePass', str(d['G3_pass_n']))
    M(f'{s}GFourTestable', NW[d['G4_testable']]); M(f'{s}GFourPass', NW[sum(v == 'pass' for v in d['G4'].values())])
    M(f'{s}EstE', str(d['G5_E12'])); M(f'{s}EstS', str(d['G5_S11'])); M(f'{s}Status', SM['score_status'][k])
M('Kill', 'yes' if SM['kill'] else 'no')
mx = lambda key: max(abs(P[n]['G2'][key]) for n in P)
M('SODerMax', f(mx('SO_mean'), 3)); M('XCCDerMax', f(mx('XCC24_mean'), 3))
M('SOMin', f(min(P[n]['SO'] for n in P))); M('SOMax', f(max(P[n]['SO'] for n in P)))
M('SORelMin', f(min(P[n]['SO_rel'] for n in P))); M('SORelMax', f(max(P[n]['SO_rel'] for n in P)))
M('XCCZMin', f(min(P[n]['XCC_z'] for n in P), 1))
M('SOSemMin', f(min(P[n]['G3']['SO_sem_sd'] for n in P), 0)); M('SOArbMax', f(max(P[n]['G3']['SO_arb_sd'] for n in P), 1))
M('XCCSemMin', f(min(P[n]['G3']['XCC24_sem_sd'] for n in P), 0)); M('XCCArbMax', f(max(P[n]['G3']['XCC24_arb_sd'] for n in P), 1))
body = ('\\begin{tabular}{@{}lccccccccc@{}}\n\\toprule\nModel & $\\rho$ & $\\eta^2$ & SO$_{\\mathrm{null}}$ & rel & XCC$_{24}$ & $z$ & G2 SO / XCC & G3 SO sem / arb & F1-partial \\\\\n\\midrule\n')
for n in ORDER:
    x = P[n]
    body += (f'{NAME[n]} & {mm(f(x["rho"]))} & {mm(f(x["eta2"]))} & {mm(f(x["SO"], 3))} & {mm(f(x["SO_rel"]))} & {mm(f(x["XCC24"], 3))} & {mm(f(x["XCC_z"], 1))} & '
             f'{mm(f(x["G2"]["SO_mean"], 3))} / {mm(f(x["G2"]["XCC24_mean"], 3))} & {mm(f(x["G3"]["SO_sem_sd"], 0))} / {mm(f(x["G3"]["SO_arb_sd"], 1))} & {mm(f(x["F1_partial"], 3))} \\\\\n')
body += '\\midrule\n\\multicolumn{10}{@{}l}{\\emph{True DINO (values only)}}\\\\\n'
for n, x in G['dino'].items():
    body += f'{NAME[n]} & {mm(f(x["rho"]))} & {mm(f(x["eta2"]))} & {mm(f(x["SO"], 3))} & {mm(f(x["SO_rel"]))} & {mm(f(x["XCC24"], 3))} & {mm(f(x["XCC_z"], 1))} & -- & -- & {mm(f(x["F1_partial"], 3))} \\\\\n'
write('tab_r5_gates.tex', body + '\\bottomrule\n\\end{tabular}\n')

# ---- worlds (G4 and descriptive B/M/D)
body = '\\begin{tabular}{@{}llcccc@{}}\n\\toprule\nBase & Score & G4: estimable rows, $\\max/\\min$ & World B range & World M range & World D range \\\\\n\\midrule\n'
for b in BASES:
    w = G['worlds'][b]
    for k, ek in (('SO', 'SO_est'), ('XCC24', 'XCC_est')):
        g4 = w['G4'][k]; cell = f'{g4["n_est"]}/12, ' + (mm(f(g4['ratio'], 3)) + f' ({g4["status"]})' if g4['ratio'] is not None else 'not estimable')
        rng = []
        for W in 'BMD':
            v = [r[k] for r in w['rows'][W] if r[ek]]
            rng.append(f'{mm(f(min(v), 3))}--{mm(f(max(v), 3))} ({len(v)})' if v else '--')
        body += f'{NAME[b]} & {"SO$_{\\mathrm{null}}$" if k == "SO" else "XCC$_{24}$"} & {cell} & ' + ' & '.join(rng) + ' \\\\\n'
write('tab_r5_worlds.tex', body + '\\bottomrule\n\\end{tabular}\n')
relC = [r['SO_rel'] for b in BASES for r in G['worlds'][b]['rows']['C']]
M('WorldCRelMax', f(max(relC))); M('WorldCRelMin', f(min(relC), 3))
for k, ek in (('SO', 'SO_est'), ('XCC24', 'XCC_est')):
    sp = []
    for b in BASES:
        for W in 'MD':
            v = [r[k] for r in G['worlds'][b]['rows'][W] if r[ek]]
            if len(v) >= 2: sp.append(max(v) / min(v))
    M(f'{SN[k]}MDRatio', f(max(sp), 2))

# ---- confirmatory
LBL = {'ORGANISATION-TRACKS': 'ORGANISATION-TRACKS', 'ORGANISATION-DOES-NOT-TRACK': 'DOES-NOT-TRACK', 'INCONCLUSIVE': 'INCONCLUSIVE'}
body = '\\begin{tabular}{@{}llcccc@{}}\n\\toprule\nScore & Set & $n$ & $\\tau$ vs SING [95\\% CI] & $\\tau(\\cdot,\\rho)$ & partial $r$ given $\\rho$ \\\\\n\\midrule\n'
for k in ('SO', 'XCC24'):
    if k not in C: continue
    for s, sk in (('E12', 'E'), ('S11', 'S'), ('all13', 'A')):
        x = C[k][s]; s_ = SN[k]
        M(f'{s_}Tau{sk}', f(x['tau']['tau'])); M(f'{s_}Tau{sk}CI', ci(x['tau'])); M(f'{s_}Tau{sk}BCa', ci(x['tau'], 'bca'))
        M(f'{s_}Rho{sk}', f(x['tau_vs_rho'])); M(f'{s_}Eta{sk}', f(x['tau_vs_eta2'])); M(f'{s_}Part{sk}', f(x['partial_given_rho']['r'])); M(f'{s_}Part{sk}CI', ci(x['partial_given_rho']))
        body += f'{"SO$_{\\mathrm{null}}$" if k == "SO" else "XCC$_{24}$"} & {s} & {x["n"]} & {tci(x["tau"])} & {mm(f(x["tau_vs_rho"]))} & {mm(f(x["partial_given_rho"]["r"]) + "\\ " + ci(x["partial_given_rho"]))} \\\\\n'
    M(f'{SN[k]}Label', LBL[C['outcome'][k]])
write('tab_r5_confirm.tex', body + '\\bottomrule\n\\end{tabular}\n')
I = C['inheritance']
M('InhLow', str(len(I['low']))); M('InhHigh', str(len(I['estimable']) - len(I['low']))); M('InhN', str(len(I['estimable']))); M('InhShare', f(100 * I['share'], 0)); M('InhStatement', I['statement'])
M('InhPlantMin', f(min(I['plant_partial_005'].values()), 3)); M('InhPlantCheck', 'pass' if I['plant_check'] else 'fail')
M('FOneMin', f(min(P[n]['F1_partial'] for n in P), 3)); M('FOneMax', f(max(P[n]['F1_partial'] for n in P), 3))

# ---- round-5 ledger
q = lambda k: mac[k]
L = [('R5-cal', 'world residuals permuted across images (seed 99000); report every changed value',
      f'{q("CalChanged")} of {q("CalTotal")} values change; content-diagnostic estimators: {q("CalDiagOld")} before, {q("CalDiagNew")} after'),
     ('R5-G1', 'exact invariance to $\\beta\\in\\{0.1,10\\}$ and orthogonal maps', f'SO {q("SOGOne")}, XCC {q("XCCGOne")}'),
     ('R5-G2', 'class-mean derangement: fail on $\\le2$ models', f'fails: SO {q("SOGTwoFail")}, XCC {q("XCCGTwoFail")} (max $|$mean$|$ ${q("SODerMax")}$, ${q("XCCDerMax")}$)'),
     ('R5-G3', 'world S: semantic $\\ge2$ SD, arbitrary $\\le1$ SD on $\\ge11/13$', f'SO {q("SOGThreePass")}/13, XCC {q("XCCGThreePass")}/13'),
     ('R5-G4', 'corrected world C: $\\max/\\min\\le1.5$; kill if it fails on $\\ge2$ bases', f'SO testable on {q("SOGFourTestable")} base (pass): not testable; XCC testable on {q("XCCGFourTestable")}, passes on {q("XCCGFourPass")}'),
     ('R5-G5', 'estimable on $\\ge9$ of E12 and $\\ge8$ of S11', f'SO {q("SOEstE")}/{q("SOEstS")}, XCC {q("XCCEstE")}/{q("XCCEstS")}; no kill'),
     ('R5-SO', 'ORGANISATION-TRACKS ($\\tau\\ge0.6$ on E12 and S11) / DOES-NOT-TRACK ($<0.3$ on both) / INCONCLUSIVE',
      f'{q("SOLabel")} (${q("SOTauE")}$ {q("SOTauECI")}, ${q("SOTauS")}$ {q("SOTauSCI")})'),
     ('R5-XCC', 'same bars, secondary', f'{q("XCCLabel")} (${q("XCCTauE")}$, ${q("XCCTauS")}$)'),
     ('R5-inh', 'INHERITED if F1-partial $\\le0.05$ on $\\ge75\\%$; plant check $\\ge0.1$', f'{q("InhStatement")} ({q("InhLow")}/{q("InhN")}, {q("InhShare")}\\%); plant check {q("InhPlantCheck")}')]
body = '\\begin{tabular}{@{}lp{0.42\\linewidth}p{0.45\\linewidth}@{}}\n\\toprule\nExp. & Pre-declared criterion (short) & Outcome \\\\\n\\midrule\n'
body += ''.join(f'{a} & {b} & {c} \\\\\n' for a, b, c in L)
write('tab_prereg_r5.tex', body + '\\bottomrule\n\\end{tabular}\n')
write('numbers_r5.tex', ''.join(f'\\newcommand{{\\F{k}}}{{{v}}}\n' for k, v in mac.items()))
print('r5 tables written;', len(mac), 'macros')
