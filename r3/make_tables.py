def f(x, n=2):
    """Math-mode number string (no $): minus sign as '-', tiny values as a{\\times}10^{e}."""
    if x is None: return '--'
    if x != 0 and abs(x) < 10 ** (-n):
        m, e = f'{x:.1e}'.split('e'); return f'{m}{{\\times}}10^{{{int(e)}}}'
    return f'{x:.{n}f}'


def mm(x): return '--' if x == '--' else f'${x}$'


def ci(d, key='pct', n=2): return f'[{f(d[key][0], n)},{f(d[key][1], n)}]'


def tci(d, n=2): return '--' if d is None else mm(f'{f(d["tau"], n)}\\ {ci(d, "pct", n)}')


def write(name, body):
    open(os.path.join(OUT, name), 'w').write('% generated by r3/make_tables.py -- do not edit\n' + body)


