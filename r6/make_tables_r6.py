"""Generate the round-6 LaTeX macros and tables from r6/results/R6_summary.json (no private inputs).
Writes paper_workshop/tables/numbers_r6.tex and tab_{r6_audit,r6_cross,r6_worlds,prereg_r6}.tex.
Usage: python r6/make_tables_r6.py  (after r6/verdicts_r6.py; run after r4/make_tables_r4.py)."""
import os, sys, json, math
R = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
sys.path.insert(0, os.path.join(R, 'r4'))
from make_tables_r4 import f, mm, ci, NAME  # noqa: E402
OUT = os.path.join(R, 'paper_workshop', 'tables')
S = json.load(open(os.path.join(R, 'r6', 'results', 'R6_summary.json'))); SC = S['scores']; CNT = S['counting']
PRIMARY = ('ViM', 'ActSub', 'CORE', 'Vinfo'); DESCR = ('ViM_s', 'CORE_ker', 'Vinfo_corr', 'NuSA')
LAB = dict(ViM='ViM', ActSub='ActSub $S_{\\to}$', CORE='CORE $S_{\\mathrm{mem}}$', Vinfo='$\\mathcal{V}$-info (class)',
           ViM_s='ViM score $s$', CORE_ker='CORE on $\\Pi f$', Vinfo_corr='$\\mathcal{V}$-info (correct)', NuSA='NuSA share')
MK = dict(ViM='Vim', ActSub='Act', CORE='Core', Vinfo='Vinfo', ViM_s='VimS', CORE_ker='CoreKer', Vinfo_corr='VinfoCorr', NuSA='Nusa')
VS = {'ENERGY-DRIVEN': 'energy-driven', 'NOT ENERGY-DRIVEN': 'not energy-driven', 'MIXED': 'mixed', 'CONTENT-RESPONSIVE': 'responsive',
      'CONTENT-BLIND': 'blind', 'PARTIAL': 'partial', 'NO VERDICT (G5)': 'no verdict'}
NW = ('zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven', 'twelve', 'thirteen')
mac = {}
def M(k, v): mac[k] = v
def write(name, body): open(os.path.join(OUT, name), 'w').write('% generated by r6/make_tables_r6.py -- do not edit\n' + body)
def g(v, d=2): return '--' if v is None or (isinstance(v, float) and not math.isfinite(v)) else mm(f(v, d))

# ---- main audit table: verdict statistics
body = ('\\begin{tabular}{@{}lccccccll@{}}\n\\toprule\n & \\multicolumn{2}{c}{estimable} & \\multicolumn{2}{c}{$\\tau_{\\mathrm{EQ}}$} & & & \\multicolumn{2}{c}{verdict} \\\\\n'
        'Score & E12 & S11 & E12 & S11 & med.\\ $R_B$ & $|C_1|{\\ge}2$ / $|\\Delta_{\\mathrm{arb}}|{\\ge}2$ & energy & content \\\\\n\\midrule\n')
for k in PRIMARY + DESCR:
    b = SC[k]; c = {a: int(v) for a, v in b['counts'].items()}
    if k == DESCR[0]: body += '\\midrule\n\\multicolumn{9}{@{}l}{\\emph{Descriptive, not counted}} \\\\\n'
    body += (f'{LAB[k]} & {b["n_E12"]} & {b["n_S11"]} & {g(b["tau_EQ"]["E12"])} & {g(b["tau_EQ"]["S11"])} & {g(b["R_B_median"])} & '
             f'{c["C1_ge2"]} / {c["plant_ge2"]} & {VS[b["energy_verdict"]]} & {VS[b["content_verdict"]]} \\\\\n')
write('tab_r6_audit.tex', body + '\\bottomrule\n\\end{tabular}\n')

# ---- cross-model table (descriptive)
body = '\\begin{tabular}{@{}lccccc@{}}\n\\toprule\nScore & $\\tau$ E12 & $\\tau$ S11 & $\\tau$ all 13 & $\\tau$ with $\\rho$ (E12 / S11) & partial given $\\rho$ (E12 / S11) \\\\\n\\midrule\n'
for k in PRIMARY + DESCR:
    cm = SC[k]['cross_model']
    if k == DESCR[0]: body += '\\midrule\n'
    cell = lambda s: mm(f'{f(cm[s]["tau_sing"]["tau"])}\\ {ci(cm[s]["tau_sing"])}') if s in cm else '--'
    rh = ' / '.join(g(cm[s]['tau_rho']) if s in cm else '--' for s in ('E12', 'S11'))
    pa = ' / '.join(g(cm[s]['partial_given_rho']['r']) if s in cm else '--' for s in ('E12', 'S11'))
    body += f'{LAB[k]} & {cell("E12")} & {cell("S11")} & {cell("all13")} & {rh} & {pa} \\\\\n'
write('tab_r6_cross.tex', body + '\\bottomrule\n\\end{tabular}\n')

# ---- worlds (descriptive)
bases = list(SC['ViM']['worlds'])
body = '\\begin{tabular}{@{}l' + 'cccc' * len(bases) + '@{}}\n\\toprule\n & ' + ' & '.join(f'\\multicolumn{{4}}{{c}}{{{NAME[b]}}}' for b in bases) + ' \\\\\n'
body += 'Score & ' + ' & '.join(['C ratio', 'C $\\tau_\\rho$', 'M $\\tau_L$', 'D $\\tau_L$'] * len(bases)) + ' \\\\\n\\midrule\n'
for k in PRIMARY + DESCR:
    if k == DESCR[0]: body += '\\midrule\n'
    cells = []
    for b in bases:
        w = SC[k]['worlds'][b]; r = w['C_ratio']
        cells += ['$\\infty$' if not math.isfinite(r) else mm(f(r)) + ('' if w['C_pass'] else '$^{*}$'), g(w['C_tau_rho']), g(w['M_tau_L']), g(w['D_tau_L'])]
    body += f'{LAB[k]} & ' + ' & '.join(cells) + ' \\\\\n'
write('tab_r6_worlds.tex', body + '\\bottomrule\n\\end{tabular}\n')

# ---- macros
M('RSixClaim', CNT['claim']); M('RSixK', str(CNT['k'])); M('RSixN', str(CNT['n'])); M('RSixKw', NW[CNT['k']]); M('RSixNw', NW[CNT['n']])
M('RSixContentMeasurable', 'yes' if CNT['content_measurable'] else 'no'); M('RSixNGood', str(CNT['n_not_energy_and_responsive']))
M('RSixMaxDlogit', (lambda a: f'{a[0]}\\times10^{{{int(a[1])}}}')(f'{S["max_dlogit"]:.1e}'.split('e')) if S['max_dlogit'] > 0 else '0'); M('RSixNModels', str(len(S['models'])))
for k in PRIMARY + DESCR:
    b = SC[k]; p = MK[k]; cm = b['cross_model']
    M(f'{p}Energy', VS[b['energy_verdict']]); M(f'{p}Content', VS[b['content_verdict']])
    M(f'{p}EqE', f(b['tau_EQ']['E12'])); M(f'{p}EqS', f(b['tau_EQ']['S11'])); M(f'{p}RB', f(b['R_B_median'])); M(f'{p}EO', f(b['tau_EO_median']))
    M(f'{p}ConeHi', str(int(b['counts']['C1_ge2']))); M(f'{p}PlantHi', str(int(b['counts']['plant_ge2'])))
    M(f'{p}ConeLo', str(int(b['counts']['C1_le1']))); M(f'{p}PlantLo', str(int(b['counts']['plant_le1'])))
    M(f'{p}NEst', str(len(b['estimable']))); M(f'{p}NoisyN', str(sum(abs(v) > 1 for v in b['C2'].values()))); M(f'{p}EstE', str(b['n_E12'])); M(f'{p}EstS', str(b['n_S11']))
    M(f'{p}Noisy', 'yes' if b['C2_noisy'] else 'no')
    for s, sk in (('E12', 'E'), ('S11', 'S'), ('all13', 'A')):
        if s in cm:
            M(f'{p}Tau{sk}', f(cm[s]['tau_sing']['tau'])); M(f'{p}Tau{sk}CI', ci(cm[s]['tau_sing'])); M(f'{p}Rho{sk}', f(cm[s]['tau_rho'])); M(f'{p}Part{sk}', f(cm[s]['partial_given_rho']['r'])); M(f'{p}Part{sk}CI', ci(cm[s]['partial_given_rho']))
    M(f'{p}Track', b.get('tracks_sing', 'n/a'))
    wc = [w['C_pass'] for w in b['worlds'].values()]; M(f'{p}WCPass', NW[sum(wc)])
# ---- round-6 ledger
VE = {'ENERGY-DRIVEN': 'ENERGY-DRIVEN', 'NOT ENERGY-DRIVEN': 'NOT ENERGY-DRIVEN', 'MIXED': 'MIXED', 'NO VERDICT (G5)': 'no verdict (G5)'}
body = '\\begin{tabular}{@{}p{0.2\\linewidth}p{0.47\\linewidth}p{0.27\\linewidth}@{}}\n\\toprule\nTest & Criterion & Outcome \\\\\n\\midrule\n'
body += f'G5 estimability & SD$_{{\\mathrm{{boot}}}}\\le0.1\\times$ range; verdict needs $\\ge$9 E12 and $\\ge$8 S11 & ' + '; '.join(f'{LAB[k]}: {SC[k]["n_E12"]}/{SC[k]["n_S11"]}' for k in PRIMARY) + ' \\\\\n'
for k in PRIMARY:
    b = SC[k]; c = {a: int(v) for a, v in b['counts'].items()}
    body += (f'{LAB[k]}, energy & ENERGY-DRIVEN if $\\tau_{{\\mathrm{{EQ}}}}<0.3$ on both sets and median $R_B\\ge0.5$; NOT if $\\ge0.6$ and $\\le0.1$ & '
             f'{VE[b["energy_verdict"]]} ($\\tau_{{\\mathrm{{EQ}}}}$ {g(b["tau_EQ"]["E12"])} / {g(b["tau_EQ"]["S11"])}, $R_B$ {g(b["R_B_median"])}) \\\\\n')
    body += (f'{LAB[k]}, content & RESPONSIVE if $|C_1|\\ge2$ and $|\\Delta_{{\\mathrm{{arb}}}}|\\ge2$ on $\\ge$10 of 13; BLIND if both $\\le1$ on $\\ge$10 & '
             f'{b["content_verdict"].lower() if b["verdict_possible"] else "no verdict (G5)"} ({c["C1_ge2"]} / {c["plant_ge2"]} of 13) \\\\\n')
body += f'Counting rule & GENERAL if $k\\ge3$ ($n{{=}}4$) or $k\\ge2$ ($n{{=}}3$); DESIGN-DEPENDENT if $n{{=}}4$, $k{{=}}2$; SING-SPECIFIC if $k\\le1$ & $n{{=}}{CNT["n"]}$, $k{{=}}{CNT["k"]}$: {CNT["claim"]} \\\\\n'
body += f'Content measurable & $\\ge$2 counted scores NOT ENERGY-DRIVEN and RESPONSIVE & {"yes" if CNT["content_measurable"] else "no"} ({CNT["n_not_energy_and_responsive"]}) \\\\\n'
write('tab_prereg_r6.tex', body + '\\bottomrule\n\\end{tabular}\n')

# ---- V-info penalty at the top of the grid (from the per-model files)
import glob
VC = [json.load(open(q))['vinfo_cal'] for q in sorted(glob.glob(os.path.join(R, 'r6', 'results', 'models', '*.json')))]
lab_fits = [v[f'label_{h}']['lam_rel'] for v in VC for h in 'AB']
M('RSixLamTop', str(sum(x >= 1.0 for x in lab_fits))); M('RSixLamN', str(len(lab_fits)))

write('numbers_r6.tex', ''.join(f'\\newcommand{{\\R{k}}}{{{v}}}\n' for k, v in mac.items()))
print('r6 tables written;', len(mac), 'macros')
